/* =====================================================================
   FIELD — recorded natural ambience over the synthesized engine
   ===================================================================== */
// Real field recordings for the natural sounds the synthesized engine used to fake: night insects,
// wind in the leaves, the stream, the waterfall, crows, morning birds. CC0 / public domain only;
// sources, licences and every edit are in assets/audio/manifest.json, the method and the search in
// docs/knowledge/07-audio-sources.md. Synthesis stays for music and magic (CLAUDE.md).
//
//   import { createFieldAmbience } from './audio/field.js';
//   import night from '../assets/audio/night.mp3'; ...        // esbuild loader { '.mp3': 'dataurl' }
//   const amb = createFieldAmbience(AU, { sources: { night, night2, wind, stream, fall, crow, birds } });
//   amb.load();                      // after AU.init(); decodes one file at a time; never throws
//   amb.update(dt, { waterDist });   // every frame, after AU.update()
//
// Everything plays into AU.ambBus() (dry + room send), so the engine's nearness low-pass, the
// far-muffling, the indoor/cinematic trims and AU.duck() apply exactly as to the synthesized layers.
// A synthesized layer is silenced (AU.mute) only once the recording that replaces it has decoded;
// a missing or undecodable file leaves its synthesized counterpart playing.
//
// extra (all optional, per frame):
//   waterDist   metres to the waterfall (default: from the engine's `fall`, 1 = 20 m; else silent)
//   streamDist  metres to the stream (default: from `stream`, else the engine's `water`, else waterDist)
//   stream      0..1 stream nearness, instead of streamDist
//   waterPan    -1..1 direction of the water
// Layers by time of day: dusk = higurashi chorus (only if the CC BY layer was approved and built,
// otherwise the engine's synthesized higurashi keeps playing); night = two insect choruses that trade
// places slowly; morning = sparse bird calls. Wind and water play at any hour.

// Generated by tools/audio/build_field.py: loop points (s) and sprite slices [start, dur] (s).
// META:BEGIN (generated, do not edit by hand)
const META = {"night":{"kind":"loop","loopStart":0.25,"loopEnd":30.25,"dur":30.5},"night2":{"kind":"loop","loopStart":0.25,"loopEnd":20.25,"dur":20.5},"wind":{"kind":"loop","loopStart":0.25,"loopEnd":27.75,"dur":28.0},"stream":{"kind":"loop","loopStart":0.25,"loopEnd":20.25,"dur":20.5},"fall":{"kind":"loop","loopStart":0.25,"loopEnd":16.25,"dur":16.5},"crow":{"kind":"sprite","segs":{"crow_a":[0.15,2.27],"crow_b":[2.87,1.62],"crow_a1":[0.15,0.8],"crow_a3":[1.73,0.69],"crow_b1":[2.87,0.45],"crow_b2":[3.45,0.44]},"dur":4.64},"birds":{"kind":"sprite","segs":{"bulbul_a":[0.15,2.63],"bulbul_b":[3.23,1.85],"tit_a":[5.53,2.83],"tit_b":[8.81,2.76],"ugu_a":[12.02,2.02],"ugu_b":[14.49,2.2],"ugu_c":[17.14,2.6]},"dur":19.89}};
// META:END

// The synthesized engine layers each recording replaces (AU.mute names).
const REPLACES = {
  night: ['suzu'], night2: ['suzu'], wind: ['wind', 'leaves'], stream: ['stream'], fall: ['fall'],
  crow: ['crow'], birds: ['ugu', 'tit'], dusk: ['higu'], higu: ['higu'],
};

// Mix. Bed files are normalized to -23 LUFS, event slices to -18 LUFS; `db` is the gain into the
// engine's ambience input. Resulting loudness there (the engine's own beds, estimated, in brackets):
// night insects about -33 LUFS [synthesized suzumushi -38], wind at wind 0.3 about -32 [-32],
// waterfall at 35 m about -37, "soft distant water" (11 m and closer -26 [fall=1: -21.5]), stream at
// 3 m and closer about -24 [water=1: -20.5]. Synthesized levels: tools/audio/synth_levels.py.
const MIX = {
  night: { db: -9, wet: 0.12, spread: 0.55 },   // Akiyoshidai: 4 kHz trills, 2.6 kHz pulses
  night2: { db: -12, wet: 0.12, spread: 0.7 },  // Tsushima long grass: katydid band, 5 kHz pulses
  dusk: { db: -7, wet: 0.2, spread: 0.6 },      // CC BY higurashi chorus (optional)
  wind: { db: -9, wet: 0.06, spread: 0.7 },     // scales with the engine's wind (0.3 = reference)
  stream: { db: -6, wet: 0.1, spread: 0.35, ref: 6 },  // level at `ref` metres, 1/d beyond
  fall: { db: -8, wet: 0.1, spread: 0.25, ref: 20 },   // level at `ref` metres, 1/d beyond
  crow: { db: -10 }, birds: { db: -14 }, higu: { db: -10 },
};

const clamp = (v, a, b) => (v < a ? a : v > b ? b : v);
const num = (v, d) => (typeof v === 'number' && Number.isFinite(v) ? v : d);
const rnd = (a, b) => a + Math.random() * (b - a);
const dbl = (db) => Math.pow(10, db / 20);
const circ = (h) => ((h % 24) + 24) % 24;
const DEBUG = typeof location !== 'undefined' && /[?&]audiodebug=1/.test(location.search);
// 1 inside the daily window [a, b] (hours, may wrap midnight), easing in and out over f hours.
function win(h, a, b, f) {
  h = circ(h);
  const inside = a <= b ? h >= a && h <= b : h >= a || h <= b;
  if (!inside) return 0;
  const t = Math.min(circ(h - a), circ(b - h)) / f;
  return t >= 1 ? 1 : t * t * (3 - 2 * t);
}

// Bytes of a data: URL without fetch() (a strict connect-src policy may block fetching data: URLs).
function bytesOf(url) {
  const comma = url.indexOf(',');
  if (url.slice(0, 5) !== 'data:' || comma < 0) return null;
  const head = url.slice(5, comma), body = url.slice(comma + 1);
  if (!/;base64$/i.test(head)) return new TextEncoder().encode(decodeURIComponent(body)).buffer;
  const bin = atob(body), out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out.buffer;
}
async function arrayBufferOf(url) {
  const b = bytesOf(url);
  if (b) return b;
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return r.arrayBuffer();
}
function decode(ctx, buf) { // promise and callback forms (older Safari only calls back)
  return new Promise((res, rej) => {
    try { const p = ctx.decodeAudioData(buf, res, rej); if (p && p.then) p.then(res, rej); } catch (e) { rej(e); }
  });
}

export function createFieldAmbience(AU, { sources = {}, meta = META } = {}) {
  let ctx = null, bus = null, loading = null, enabled = true, now = 0;
  const buffers = {};          // name -> AudioBuffer
  const beds = {};             // name -> bed state
  const muted = new Set();     // engine layers silenced by us
  const live = new Set();      // event voices in flight
  const last = new WeakMap();  // change-detected automation targets
  const S = { gust: 1, nextGust: 0, mixA: 0.7, nextMix: 0, cool: {}, pending: [] };

  function tgt(p, v, tc) {
    if (!p || !Number.isFinite(v)) return;
    const prev = last.get(p);
    if (prev !== undefined && Math.abs(prev - v) <= 1e-5 + Math.abs(v) * 0.004) return;
    last.set(p, v);
    try { p.setTargetAtTime(v, ctx.currentTime, Math.max(0.01, tc)); } catch (e) { /* ignore */ }
  }

  /* ---------- beds: two voices of one mono loop, panned apart, 0.382 of a loop apart ---------- */
  // Not half a loop: then the mix would repeat mirrored every L/2. Same playback rate on purpose:
  // detuned copies would beat on the steady insect trills and slowly flange as they drift in phase.
  function makeBed(name) {
    const m = MIX[name] || {}, out = ctx.createGain(), lp = ctx.createBiquadFilter(), send = ctx.createGain();
    out.gain.value = 0; send.gain.value = m.wet || 0;
    lp.type = 'lowpass'; lp.frequency.value = 20000; lp.Q.value = -3; // Q in dB here: -3 = Butterworth
    lp.connect(out); out.connect(bus.inp); out.connect(send); send.connect(bus.wet);
    beds[name] = { name, m, out, lp, send, voices: [], live: false, idle: 0, level: 0, tc: 1 };
  }
  function startVoices(b) {
    const buf = buffers[b.name], mm = meta[b.name], L = mm.loopEnd - mm.loopStart, sp = b.m.spread || 0.5;
    const off0 = rnd(0, L), t = ctx.currentTime + 0.02;
    for (let i = 0; i < 2; i++) {
      const s = ctx.createBufferSource(), pan = ctx.createStereoPanner(), g = ctx.createGain();
      s.buffer = buf; s.loop = true; s.loopStart = mm.loopStart; s.loopEnd = mm.loopEnd;
      pan.pan.value = i ? sp : -sp;
      g.gain.value = Math.SQRT1_2; // two uncorrelated halves: the sum keeps the file's loudness
      s.connect(g); g.connect(pan); pan.connect(b.lp);
      s.start(t, mm.loopStart + ((off0 + i * L * 0.382) % L));
      b.voices.push({ s, g, pan });
    }
    b.live = true; b.idle = 0;
  }
  function stopVoices(b) {
    for (const v of b.voices) {
      try { v.s.stop(); } catch (e) { /* ignore */ }
      for (const n of [v.s, v.g, v.pan]) { try { n.disconnect(); } catch (e) { /* ignore */ } }
    }
    b.voices = []; b.live = false;
  }
  // Sources run only while audible: started on demand, stopped once the gain has decayed
  // (six time constants after the target reached zero) so nothing is ever cut off mid-sound.
  function bedLevel(name, level, dt, tc) {
    const b = beds[name];
    if (!b) return;
    level = enabled ? level : 0;
    b.level = level; b.tc = tc;
    if (level > 1e-5) { if (!b.live) startVoices(b); b.idle = 0; }
    else if (b.live && (b.idle += dt) > Math.max(4, 6 * tc)) stopVoices(b);
    tgt(b.out.gain, level, tc);
  }

  /* ---------- events: slices of a sprite, placed at a distance and a direction ---------- */
  function playSlice(name, slice, o) {
    const buf = buffers[name], seg = meta[name] && meta[name].segs[slice];
    if (!buf || !seg || !bus) return 0;
    const t = ctx.currentTime + 0.03, rate = o.rate || 1, sub = !!o.sub;
    // Whole slices carry their own fades and sit in silence; sub-slices are cut out of a longer call.
    const lead = sub ? 0 : 0.06, tail = sub ? 0 : 0.1;
    const start = Math.max(0, seg[0] - lead), dur = seg[1] + lead + tail, end = t + dur / rate;
    const s = ctx.createBufferSource(), g = ctx.createGain(), lp = ctx.createBiquadFilter();
    const pan = ctx.createStereoPanner(), send = ctx.createGain();
    s.buffer = buf; s.playbackRate.value = rate;
    lp.type = 'lowpass'; lp.Q.value = -3; lp.frequency.value = clamp(o.lp || 16000, 200, 20000);
    pan.pan.value = clamp(o.pan || 0, -1, 1); send.gain.value = o.wet || 0;
    g.gain.setValueAtTime(0, t);
    g.gain.linearRampToValueAtTime(o.gain, t + (sub ? 0.012 : 0.004));
    g.gain.setValueAtTime(o.gain, Math.max(t + 0.02, end - (sub ? 0.05 : 0.02)));
    g.gain.linearRampToValueAtTime(0, end);
    s.connect(g); g.connect(lp); lp.connect(pan); pan.connect(bus.inp); pan.connect(send); send.connect(bus.wet);
    const v = { kind: o.kind, end };
    live.add(v);
    s.onended = () => { live.delete(v); for (const n of [s, g, lp, pan, send]) { try { n.disconnect(); } catch (e) { /* ignore */ } } };
    s.start(t, start, dur);
    s.stop(end + 0.05);
    return dur / rate;
  }
  const busy = (kind) => { let n = 0; for (const v of live) if (v.kind === kind && v.end > now) n++; return n; };
  // A creature d metres away: 1/d level (re 15 m), air and foliage low-pass, more room.
  const place = (d, db) => ({ gain: dbl(db) * clamp(15 / d, 0.05, 1.5), lp: clamp(16000 * Math.pow(15 / d, 0.8), 1500, 16000), wet: clamp(0.15 + 0.5 * (1 - 15 / d), 0.1, 0.65) });

  const CROWS = ['crow_a', 'crow_b', 'crow_a', 'crow_b', 'crow_a1', 'crow_a3', 'crow_b1', 'crow_b2'];
  function crowCall(act, answer) {
    const slice = CROWS[(Math.random() * CROWS.length) | 0], sub = /\d$/.test(slice);
    const p = place(answer ? rnd(40, 160) : rnd(25, 120), MIX.crow.db + rnd(-3, 2));
    const pan = answer ? clamp(-answer.pan + rnd(-0.4, 0.4), -1, 1) : rnd(-0.95, 0.95);
    const dur = playSlice('crow', slice, { kind: 'crow', sub, pan, rate: rnd(0.96, 1.04), ...p, gain: p.gain * act });
    if (dur > 0 && !answer && Math.random() < 0.35) S.pending.push({ t: now + dur + rnd(0.8, 3.5), fn: () => crowCall(act, { pan }) });
  }
  const BIRDS = [ // [slice, weight, cooldown s]
    ['bulbul_a', 3, 14], ['bulbul_b', 2, 14], ['tit_a', 2, 10], ['tit_b', 2, 10],
    ['ugu_a', 1.2, 20], ['ugu_b', 1.2, 20], ['ugu_c', 1.2, 20],
  ];
  function birdCall(act) {
    const segs = meta.birds && meta.birds.segs;
    const ok = BIRDS.filter(([s]) => segs && segs[s] && !(S.cool[s] > now));
    if (!ok.length) return;
    let r = Math.random() * ok.reduce((a, b) => a + b[1], 0), pick = ok[0];
    for (const b of ok) { if ((r -= b[1]) <= 0) { pick = b; break; } }
    S.cool[pick[0]] = now + pick[2] * rnd(0.8, 1.6);
    const p = place(rnd(12, 70), MIX.birds.db + rnd(-3, 2));
    playSlice('birds', pick[0], { kind: 'birds', pan: rnd(-0.9, 0.9), rate: rnd(0.97, 1.03), ...p, gain: p.gain * act });
  }
  function higuCall(act, chain = 0) {
    const segs = meta.higu && Object.keys(meta.higu.segs);
    if (!segs || !segs.length) return;
    const p = place(rnd(15, 60), MIX.higu.db + rnd(-3, 1));
    const dur = playSlice('higu', segs[(Math.random() * segs.length) | 0], { kind: 'higu', pan: rnd(-0.95, 0.95), rate: rnd(0.98, 1.02), ...p, gain: p.gain * act });
    if (dur > 0 && chain < 3 && Math.random() < 0.55) S.pending.push({ t: now + dur + rnd(-1, 1.5), fn: () => higuCall(act, chain + 1) });
  }

  /* ---------- loading ---------- */
  async function loadOne(name) {
    const url = sources[name], m = meta[name];
    if (!url || !m) return false;
    try {
      const buf = await decode(ctx, await arrayBufferOf(url));
      if (m.kind === 'loop' && !(buf.duration >= m.loopEnd - 0.01)) throw new Error(`decoded ${buf.duration} s < loopEnd ${m.loopEnd} s`);
      buffers[name] = buf;
      if (m.kind === 'loop') makeBed(name);
      const names = REPLACES[name] || [];
      if (enabled && names.length) { AU.mute(names, true); for (const n of names) muted.add(n); }
      return true;
    } catch (e) {
      if (DEBUG) console.warn('field audio:', name, e);
      return false;
    }
  }
  function load() {
    if (loading) return loading;
    ctx = AU.context && AU.context();
    bus = AU.ambBus && AU.ambBus();
    if (!ctx || !bus) return Promise.resolve([]); // AU.init() has not succeeded yet: call again later
    loading = (async () => {
      const ok = [];
      // Most audible first; one file at a time, yielding between them.
      for (const name of ['wind', 'fall', 'stream', 'dusk', 'night', 'crow', 'higu', 'birds', 'night2']) {
        if (await loadOne(name)) ok.push(name);
        await new Promise((r) => setTimeout(r, 0));
      }
      return ok;
    })();
    return loading;
  }

  /* ---------- per frame ---------- */
  function update(dt, extra) {
    if (!ctx || !bus) return;
    try { step(clamp(num(dt, 1 / 60), 0, 0.25), extra && typeof extra === 'object' ? extra : {}); }
    catch (e) { if (DEBUG) console.warn('field audio:', e); } // audio never stops the game
  }
  function step(dt, x) {
    now = ctx.currentTime;
    const st = AU.state ? AU.state() : null;
    if (!st) return;
    const h = num(st.tod, 12), rain = clamp(num(st.rain, 0), 0, 1), wind = clamp(num(st.wind, 0.3), 0, 1);
    const act = clamp(num(st.act, 1), 0, 1), b = st.biome || {}, dry = 1 - 0.85 * rain;

    // Insects. Dusk: the higurashi chorus (CC BY layer, if built). Night: two choruses whose balance
    // drifts every 20-45 s, so the bed never settles into one loop.
    const duskW = (win(h, 16.8, 19.4, 0.6) + 0.7 * win(h, 4.3, 5.9, 0.4)) * dry * act;
    const nightW = win(h, 18.6, 4.8, 0.8) * dry * act;
    if (now > S.nextMix) { S.mixA = rnd(0.45, 1); S.nextMix = now + rnd(20, 45); }
    bedLevel('dusk', dbl(MIX.dusk.db) * duskW, dt, 3);
    bedLevel('night', dbl(MIX.night.db) * nightW * S.mixA, dt, 4);
    bedLevel('night2', dbl(MIX.night2.db) * nightW * (1.45 - S.mixA), dt, 4);

    // Wind in the leaves: level and brightness follow the engine's wind; slow swells on top of the
    // gusts already in the recording.
    if (now > S.nextGust) { S.gust = clamp(1 + (Math.random() - 0.5) * (0.35 + 0.7 * wind), 0.6, 1.4); S.nextGust = now + rnd(0.8, 3); }
    const open = clamp(num(b.forest, 1) + num(b.bamboo, 0) + 1.2 * num(b.meadow, 0) + num(b.shrine, 0) + 0.5 * num(b.stream, 0), 0.3, 1.3);
    bedLevel('wind', dbl(MIX.wind.db) * (0.3 + 2.3 * wind) * open * S.gust, dt, 1.2);
    if (beds.wind) tgt(beds.wind.lp.frequency, 6000 + 14000 * wind, 1.5);

    // Water by distance: 1/d level (capped close up), air and foliage low-pass, more room further away.
    const water = (name, d, pan) => {
      const bd = beds[name], m = MIX[name];
      if (!bd) return;
      d = Math.max(1, d);
      bedLevel(name, Number.isFinite(d) ? dbl(m.db) * clamp(m.ref / d, 0, 1.8) : 0, dt, 0.8);
      if (!Number.isFinite(d)) return;
      tgt(bd.lp.frequency, clamp(15000 * Math.pow((m.ref * 0.5) / d, 0.75), 900, 18000), 0.8);
      tgt(bd.send.gain, clamp(m.wet + 0.45 * (1 - m.ref / d), m.wet, 0.6), 0.8);
      if (bd.voices.length === 2) { tgt(bd.voices[0].pan.pan, clamp(pan - m.spread, -1, 1), 0.3); tgt(bd.voices[1].pan.pan, clamp(pan + m.spread, -1, 1), 0.3); }
    };
    const pan = clamp(num(x.waterPan, 0), -1, 1);
    const fallD = num(x.waterDist, num(st.fall, 0) > 0.001 ? MIX.fall.ref / st.fall : Infinity);
    let streamD = num(x.streamDist, NaN);
    if (!Number.isFinite(streamD)) {
      if (typeof x.stream === 'number') streamD = x.stream > 0.001 ? MIX.stream.ref / clamp(x.stream, 0.001, 1) : Infinity;
      else if (num(st.water, 0) > 0.001) streamD = MIX.stream.ref / st.water;
      else streamD = fallD;
    }
    water('fall', fallD, pan);
    water('stream', streamD, pan);

    // Creatures (Poisson): like the engine's own, rate and level scale with its activity (the far
    // rule: fewer, quieter calls as nearness drops) and fall with rain.
    if (enabled && act > 0.02) {
      if (buffers.crow && busy('crow') < 2) {
        const crowW = win(h, 4.7, 19.2, 0.5) * (0.35 + win(h, 4.7, 7.5, 0.6) + win(h, 16.2, 19.2, 0.6));
        if (Math.random() < crowW * dry * act * 0.02 * dt) crowCall(act);
      }
      if (buffers.birds && busy('birds') < 2) {
        const birdW = win(h, 4.8, 10.5, 0.8) + 0.3 * win(h, 10.5, 17.2, 0.8);
        if (Math.random() < birdW * dry * act * 0.11 * dt) birdCall(act);
      }
      if (buffers.higu && busy('higu') < 3 && Math.random() < duskW * 0.08 * dt) higuCall(act); // duskW includes act
    }
    for (let i = S.pending.length - 1; i >= 0; i--) {
      if (S.pending[i].t <= now) { const p = S.pending.splice(i, 1)[0]; if (enabled) p.fn(); }
    }
  }

  // A/B switch: off brings the synthesized layers back; on silences them again.
  function setEnabled(on) {
    enabled = !!on;
    const names = [];
    for (const n of Object.keys(buffers)) names.push(...(REPLACES[n] || []));
    if (names.length) AU.mute(names, enabled);
    muted.clear();
    if (enabled) for (const n of names) muted.add(n);
    else for (const b of Object.values(beds)) tgt(b.out.gain, 0, 0.5);
  }
  function stats() {
    const levels = {};
    for (const [k, b] of Object.entries(beds)) levels[k] = { level: +b.level.toFixed(5), live: b.live };
    return { loaded: Object.keys(buffers), muted: [...muted], levels, events: live.size, enabled };
  }
  return { load, update, setEnabled, stats };
}
