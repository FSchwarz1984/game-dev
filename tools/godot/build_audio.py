#!/usr/bin/env python3
# Converts the CC0 / public-domain field recordings in assets/audio/ (see its manifest.json and
# docs/knowledge/07-audio-sources.md) into the Godot project's audio files:
#   python3 -I tools/godot/build_audio.py
# - "loop" entries -> godot/audio/ambience/<name>.ogg, cut to exactly [loopStart, loopEnd] of the
#   MP3 so the whole file is the seamless loop (Godot loops an OGG sample-accurately; an MP3's
#   encoder delay would shift the seam).
# - "sprite" entries -> godot/audio/spots/<name>_<segment>.ogg, one file per named segment.
# Also writes godot/audio/SOURCES.json: every output file with its source, author and licence.
# Needs ffmpeg with libvorbis. ffmpeg decodes the MP3 gaplessly (it honours the LAME header).
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "assets", "audio")
OUT = os.path.join(ROOT, "godot", "audio")


def ffmpeg(src, dst, start, dur):
    subprocess.check_call([
        "ffmpeg", "-loglevel", "error", "-y", "-i", src, "-ss", "%.4f" % start, "-t", "%.4f" % dur,
        "-ac", "1", "-ar", "44100", "-c:a", "libvorbis", "-q:a", "5", "-map_metadata", "-1", dst])


def main():
    with open(os.path.join(SRC, "manifest.json"), encoding="utf-8") as f:
        man = json.load(f)
    os.makedirs(os.path.join(OUT, "ambience"), exist_ok=True)
    os.makedirs(os.path.join(OUT, "spots"), exist_ok=True)
    sources = {}
    for name, e in man.items():
        if name.startswith("_"):
            continue
        src = os.path.join(ROOT, e["file"])
        meta = e.get("_meta", {})
        if e.get("kind") == "loop":
            start, end = float(meta["loopStart"]), float(meta["loopEnd"])
            rel = "ambience/%s.ogg" % name
            ffmpeg(src, os.path.join(OUT, rel), start, end - start)
            sources[rel] = {"from": e["file"], "cut": [start, end], "source": e.get("source"), "edits": e.get("edits")}
        elif e.get("kind") == "sprite":
            for seg, (start, dur) in sorted(e.get("segments", {}).items()):
                rel = "spots/%s_%s.ogg" % (name, seg)
                ffmpeg(src, os.path.join(OUT, rel), float(start), float(dur))
                sources[rel] = {"from": e["file"], "cut": [start, start + dur], "sources": e.get("sources")}
    with open(os.path.join(OUT, "SOURCES.json"), "w", encoding="utf-8") as f:
        json.dump({"_about": "Generated by tools/godot/build_audio.py from assets/audio/manifest.json. "
                   "Licence policy: CC0 or public domain only.", "files": sources}, f, ensure_ascii=False, indent=1)
    for d in ("ambience", "spots"):
        for fn in sorted(os.listdir(os.path.join(OUT, d))):
            print(d + "/" + fn, os.path.getsize(os.path.join(OUT, d, fn)))


if __name__ == "__main__":
    main()
